#!/usr/bin/env node
'use strict';
// Zero dependencies. Both hosts still load standalone, prebuilt delivery files.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const shared = fs.readFileSync(path.join(root, 'ui/reader.js'), 'utf8');
const styles = fs.readFileSync(path.join(root, 'ui/reader.css'), 'utf8');
const header = '/* Generated by node scripts/build-ui.cjs. Edit ui/reader.js and ui/reader.css. */\n';
const core = `const BLOGWATCHER_STYLES = ${JSON.stringify(styles)};\n${shared}\n`;
const outputs = {
  'desktop/plugin.js': header + `import { host, ROUTES_AREA, SIDEBAR_NAV_AREA } from '@hermes/plugin-sdk';
import { createElement, useState, useEffect, useRef } from 'react';
${core}
const BlogwatcherPage = createBlogwatcherPage({ createElement, useState, useEffect, useRef }, {
  request(ctx, route, body) {
    return ctx.rest(route, body === undefined ? undefined : {
      method: 'POST', body,
      timeoutMs: route === '/scan' ? 195000 : route === '/articles/summary' ? 175000 : route === '/blogs' ? 75000 : 45000,
    });
  },
  openExternal: (ctx, url) => ctx.os.openExternal(url),
  chat: () => host.navigate('/'),
}, BLOGWATCHER_STYLES);
export default {
  id: 'hermes-blogwatcher', name: 'Blogwatcher', defaultEnabled: false,
  register(ctx) {
    ctx.register({ id: 'page', area: ROUTES_AREA, data: { path: '/blogwatcher' }, render: () => createElement(BlogwatcherPage, { ctx }) });
    ctx.register({ id: 'nav', area: SIDEBAR_NAV_AREA, data: { path: '/blogwatcher', label: 'Blogwatcher', codicon: 'rss' } });
  }
};
`,
  'dashboard/dist/index.js': header + `(function () {
'use strict';
const SDK = window.__HERMES_PLUGIN_SDK__;
${core}
const BlogwatcherPage = createBlogwatcherPage({ createElement: SDK.React.createElement, ...SDK.hooks }, {
  request(_ctx, route, body) {
    return SDK.fetchJSON('/api/plugins/hermes-blogwatcher' + route, body === undefined ? undefined : {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
    });
  },
}, BLOGWATCHER_STYLES);
window.__HERMES_PLUGINS__.register('hermes-blogwatcher', BlogwatcherPage);
})();
`,
};
let stale = false;
for (const [name, value] of Object.entries(outputs)) {
  const target = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== value) {
      console.error('Out of date: ' + name); stale = true;
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, value);
    console.log('Built ' + name);
  }
}
if (stale) { console.error('Run: node scripts/build-ui.cjs'); process.exitCode = 1; }
else if (process.argv.includes('--check')) console.log('Desktop and web deliveries match their shared source.');
