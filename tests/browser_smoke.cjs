#!/usr/bin/env node
'use strict';
// Optional real-browser verification against the actual shipped entrypoints.
// Build previews first: node scripts/preview-ui.cjs --output DIR
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { pathToFileURL } = require('node:url');
const host = process.env.HERMES_SOURCE || path.join(os.homedir(), '.hermes/hermes-agent');
const { chromium } = require(require.resolve('playwright', { paths: [path.resolve(__dirname, '..'), host] }));
const directory = path.resolve(process.argv[2] || path.join(process.env.TMPDIR || os.tmpdir(), 'blogwatcher-reader-preview'));
const checks = [], screenshots = [], contrast = [];
async function contrastRatios(page) {
  return page.locator('.bw-reader').evaluate(root => {
    const style = getComputedStyle(root);
    const color = token => {
      const probe = document.createElement('span'); root.append(probe); probe.style.color = `var(${token})`;
      const value = getComputedStyle(probe).color; probe.remove();
      const values = value.match(/[\d.]+/g).slice(0, 3).map(Number).map(v => v / 255);
      return values.map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4).reduce((sum, v, i) => sum + v * [.2126, .7152, .0722][i], 0);
    };
    const ratio = (a, b) => { const x = color(a), y = color(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); };
    return { theme: root.dataset.theme, background: style.backgroundColor, text: ratio('--bw-text', '--bw-bg'), muted: ratio('--bw-muted', '--bw-bg'), primaryButton: ratio('--bw-on-accent', '--bw-accent') };
  });
}
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  try {
    for (const surface of ['web', 'desktop']) {
      const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
      const page = await context.newPage();
      page.setDefaultTimeout(10000);
      const errors = [], network = [];
      page.on('pageerror', error => errors.push(error.message));
      page.on('request', req => { if (/^https?:/.test(req.url())) network.push(req.url()); });
      await page.goto(pathToFileURL(path.join(directory, surface + '.html')).href);
      await page.locator('.bw-article').first().waitFor();
      await page.waitForFunction(() => document.querySelector('[role="tabpanel"]').getAttribute('aria-busy') === 'false');
      assert.equal(await page.getByLabel('Appearance', { exact: true }).inputValue(), 'system');
      const originalDocumentTheme = await page.evaluate(() => document.documentElement.dataset.theme);
      const lightHost = await page.locator('.bw-reader').evaluate(el => getComputedStyle(el).backgroundColor);
      await page.getByRole('button', { name: 'Host: light', exact: true }).click();
      const darkHost = await page.locator('.bw-reader').evaluate(el => getComputedStyle(el).backgroundColor);
      assert.notEqual(lightHost, darkHost, 'follow-host appearance must react to host variable changes');
      checks.push(surface + ': follows live host theme');
      for (const theme of ['light', 'dark']) {
        await page.getByLabel('Appearance', { exact: true }).selectOption(theme);
        assert.equal(await page.locator('.bw-reader').getAttribute('data-theme'), theme);
        assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), originalDocumentTheme);
        const ratios = await contrastRatios(page); contrast.push({ surface, ...ratios });
        assert.ok(ratios.text >= 4.5, 'body text contrast');
        assert.ok(ratios.muted >= 4.5, 'metadata contrast');
        assert.ok(ratios.primaryButton >= 4.5, 'primary button contrast');
        const target = path.join(directory, surface + '-' + theme + '.png');
        await page.screenshot({ path: target }); screenshots.push(target);
      }
      checks.push(surface + ': scoped light/dark and measured text contrast');
      await page.getByLabel('Reading density').selectOption('compact');
      const compact = await page.locator('.bw-article-header').first().evaluate(el => el.getBoundingClientRect().height);
      await page.reload(); await page.locator('.bw-article').first().waitFor();
      assert.equal(await page.getByLabel('Appearance', { exact: true }).inputValue(), 'dark');
      assert.equal(await page.getByLabel('Reading density').inputValue(), 'compact');
      await page.getByLabel('Reading density').selectOption('comfortable');
      const comfortable = await page.locator('.bw-article-header').first().evaluate(el => el.getBoundingClientRect().height);
      assert.ok(comfortable > compact, 'density control must actually change row height');
      checks.push(surface + ': saved preferences and real density layout');
      await page.getByRole('button', { name: 'Hide sources', exact: true }).click();
      assert.equal(await page.locator('.bw-rail').isVisible(), false);
      await page.getByRole('button', { name: 'Show sources', exact: true }).click();
      assert.equal(await page.locator('.bw-rail').isVisible(), true);
      checks.push(surface + ': collapsible source rail');
      const unread = page.getByRole('tab', { name: 'Unread', exact: true });
      await unread.focus(); await page.keyboard.press('ArrowRight');
      assert.equal(await page.getByRole('tab', { name: 'All articles', exact: true }).getAttribute('aria-selected'), 'true');
      assert.equal(await page.getByRole('tab', { name: 'All articles', exact: true }).evaluate(el => el === document.activeElement), true);
      await page.keyboard.press('Home');
      await page.waitForFunction(() => document.querySelector('[role="tabpanel"]').getAttribute('aria-busy') === 'false');
      checks.push(surface + ': keyboard tabs and focus');
      const first = page.locator('.bw-article').filter({ has: page.getByRole('button', { name: 'A calmer way to keep up with the web', exact: true }) });
      const second = page.locator('.bw-article').filter({ has: page.getByRole('button', { name: 'Designing APIs that are easy to change', exact: true }) });
      await first.locator('.bw-article-title button').click();
      await first.locator('.bw-prose').waitFor();
      await second.locator('.bw-article-title button').click();
      await second.locator('.bw-prose').waitFor();
      assert.equal(await page.getByRole('region', { name: 'Article details', exact: true }).count(), 2);
      assert.equal(await page.evaluate(() => readerPreview.calls.filter(c => c.method === 'POST').length), 0);
      await page.locator('.bw-reader').evaluate(el => { el.scrollTop = 0; }); await page.mouse.move(0, 0);
      const readingShot = path.join(directory, surface + '-reading.png'); await page.screenshot({ path: readingShot }); screenshots.push(readingShot);
      checks.push(surface + ': multiple inline saved summaries without POSTs');
      await first.getByRole('button', { name: 'Close', exact: true }).focus();
      await page.keyboard.press('Enter');
      assert.equal(await first.locator('.bw-article-title button').evaluate(el => el === document.activeElement), true, 'closing details must restore focus to the article title');
      checks.push(surface + ': closing details restores keyboard focus');
      await second.getByRole('button', { name: 'Close', exact: true }).click();
      const distant = page.locator('.bw-article').nth(19);
      await distant.locator('.bw-article-title button').scrollIntoViewIfNeeded();
      const beforeScroll = await page.locator('.bw-reader').evaluate(el => el.scrollTop);
      await distant.locator('.bw-article-title button').click();
      await distant.getByRole('region', { name: 'Article details', exact: true }).waitFor();
      const afterScroll = await page.locator('.bw-reader').evaluate(el => el.scrollTop);
      assert.ok(Math.abs(afterScroll - beforeScroll) <= 2, `inline expansion jumped scroll: ${beforeScroll} -> ${afterScroll}`);
      await page.locator('.bw-reader').evaluate(el => { el.scrollTop = 0; });
      checks.push(surface + ': expansion preserves reading scroll position');
      await page.evaluate(() => readerPreview.setDelay(600));
      await first.getByRole('button', { name: 'Mark read', exact: true }).click();
      assert.equal(await first.getByRole('button', { name: 'Saving…', exact: true }).isDisabled(), true);
      assert.equal(await second.getByRole('button', { name: 'Mark read', exact: true }).isEnabled(), true);
      await page.waitForFunction(() => ![...document.querySelectorAll('.bw-article-title button')].some(el => el.textContent === 'A calmer way to keep up with the web'));
      await page.evaluate(() => readerPreview.setDelay(25));
      checks.push(surface + ': row-local action feedback and confirmed read state');
      await page.getByRole('button', { name: 'Interface Notes', exact: true }).click();
      await page.waitForFunction(() => document.querySelector('[role="tabpanel"]').getAttribute('aria-busy') === 'false');
      assert.ok(await page.locator('.bw-article-source').evaluateAll(els => els.every(el => el.textContent === 'Interface Notes')));
      await page.getByRole('button', { name: 'All sources', exact: true }).click();
      await page.waitForFunction(() => document.querySelector('[role="tabpanel"]').getAttribute('aria-busy') === 'false');
      checks.push(surface + ': source filtering');
      await page.evaluate(() => readerPreview.setFault('list'));
      await page.getByRole('button', { name: 'Refresh', exact: true }).first().click();
      await page.locator('.bw-banner-error').waitFor();
      assert.match(await page.locator('.bw-reading-caption').textContent(), /Count unavailable/);
      await page.evaluate(() => readerPreview.setFault(''));
      await page.getByRole('button', { name: 'Refresh', exact: true }).first().click();
      await page.locator('.bw-banner-error').waitFor({ state: 'detached' });
      checks.push(surface + ': actionable error and successful refresh recovery');
      await page.getByRole('button', { name: 'Sources', exact: true }).click();
      await page.getByLabel('Name', { exact: true }).fill('Extra source');
      await page.getByLabel('Website URL', { exact: true }).fill('https://example.org/extra');
      await page.getByRole('button', { name: 'Add source', exact: true }).click();
      await page.getByRole('heading', { name: 'Extra source', exact: true }).waitFor();
      const card = page.locator('.bw-source-card').filter({ has: page.getByRole('heading', { name: 'Extra source', exact: true }) });
      page.once('dialog', dialog => dialog.accept()); await card.getByRole('button', { name: 'Remove', exact: true }).click();
      await page.getByRole('heading', { name: 'Extra source', exact: true }).waitFor({ state: 'detached' });
      await page.locator('.bw-reader').evaluate(el => { el.scrollTop = 0; }); await page.mouse.move(0, 0);
      const sourceShot = path.join(directory, surface + '-sources.png'); await page.screenshot({ path: sourceShot }); screenshots.push(sourceShot);
      await page.getByRole('button', { name: 'Back to reading', exact: true }).click();
      checks.push(surface + ': source form, confirmed removal, and read-back');
      await page.setViewportSize({ width: 390, height: 844 });
      const toolbarRows = await page.locator('.bw-toolbar .bw-btn').evaluateAll(els => els.map(el => el.getBoundingClientRect().top));
      assert.ok(Math.max(...toolbarRows) - Math.min(...toolbarRows) <= 2, 'mobile toolbar actions must share a deliberate single row');
      assert.equal(await page.locator('.bw-rail').isVisible(), false);
      assert.equal(await page.getByLabel('Filter by source').isVisible(), true);
      const overflow = await page.locator('.bw-reader').evaluate(el => ({ scroll: el.scrollWidth, client: el.clientWidth }));
      assert.ok(overflow.scroll <= overflow.client + 1, 'narrow reading layout must not overflow horizontally');
      const narrowTitle = page.locator('.bw-article-title button').first();
      await narrowTitle.click();
      await page.getByRole('region', { name: 'Article details', exact: true }).first().waitFor();
      if (await page.getByRole('button', { name: 'Dismiss', exact: true }).count()) await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
      await page.locator('.bw-reader').evaluate(el => { el.scrollTop = 0; }); await page.mouse.move(0, 0);
      const mobileShot = path.join(directory, surface + '-mobile.png'); await page.screenshot({ path: mobileShot }); screenshots.push(mobileShot);
      await page.getByLabel('Reading density').selectOption('compact');
      const compactMobile = path.join(directory, surface + '-mobile-compact.png'); await page.screenshot({ path: compactMobile }); screenshots.push(compactMobile);
      checks.push(surface + ': responsive 390px reading and compact layout');
      await page.emulateMedia({ reducedMotion: 'reduce' });
      const transitions = await page.locator('.bw-btn').first().evaluate(el => getComputedStyle(el).transitionDuration);
      assert.equal(transitions, '0s');
      assert.deepEqual(errors, [], 'no runtime errors'); assert.deepEqual(network, [], 'preview must not contact remote publishers/models');
      checks.push(surface + ': reduced motion, zero runtime errors and zero external requests');
      await context.close();
    }
    const result = { passed: true, checks, contrast, screenshots };
    fs.writeFileSync(path.join(directory, 'browser-results.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
